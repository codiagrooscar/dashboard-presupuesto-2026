function applyGlobalDomTranslations(root) {
  if (!isEnglishActive()) return;

  const container = root || document.getElementById('appContent') || document.body;
  if (!container) return;

  // 1. Text Nodes Walker
  const walker = document.createTreeWalker(
    container,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode: function(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parentTag = node.parentElement ? node.parentElement.tagName : '';
        if (parentTag === 'SCRIPT' || parentTag === 'STYLE') return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  const nodesToReplace = [];
  let currentNode;
  while (currentNode = walker.nextNode()) {
    nodesToReplace.push(currentNode);
  }

  for (let i = 0; i < nodesToReplace.length; i++) {
    const node = nodesToReplace[i];
    const val = node.nodeValue;
    const trimmed = val.trim();

    if (window.CODIAGRO_I18N_DICT[trimmed]) {
      node.nodeValue = val.replace(trimmed, window.CODIAGRO_I18N_DICT[trimmed]);
      continue;
    }

    let newVal = val;
    for (let j = 0; j < window.CODIAGRO_I18N_PHRASES.length; j++) {
      const pair = window.CODIAGRO_I18N_PHRASES[j];
      if (newVal.indexOf(pair[0]) !== -1) {
        newVal = newVal.split(pair[0]).join(pair[1]);
      }
    }
    if (newVal !== val) {
      node.nodeValue = newVal;
    }
  }

  // 2. Attributes: placeholder, title, aria-label
  const elements = container.querySelectorAll('[placeholder], [title], [aria-label]');
  elements.forEach(function(el) {
    ['placeholder', 'title', 'aria-label'].forEach(function(attr) {
      const attrVal = el.getAttribute(attr);
      if (attrVal) {
        const trimmed = attrVal.trim();
        if (window.CODIAGRO_I18N_DICT[trimmed]) {
          el.setAttribute(attr, window.CODIAGRO_I18N_DICT[trimmed]);
        } else {
          let newAttrVal = attrVal;
          for (let j = 0; j < window.CODIAGRO_I18N_PHRASES.length; j++) {
            const pair = window.CODIAGRO_I18N_PHRASES[j];
            if (newAttrVal.indexOf(pair[0]) !== -1) {
              newAttrVal = newAttrVal.split(pair[0]).join(pair[1]);
            }
          }
          if (newAttrVal !== attrVal) {
            el.setAttribute(attr, newAttrVal);
          }
        }
      }
    });
  });

  // 3. Target elements: buttons, options, th, badges, titles
  const targetElements = container.querySelectorAll('button, option, th, span.tab-badge, .panel-title, .kpi-title, h2, h3, h4, h5');
  targetElements.forEach(function(el) {
    if (el.children.length === 0) {
      const txt = el.textContent.trim();
      if (window.CODIAGRO_I18N_DICT[txt]) {
        el.textContent = window.CODIAGRO_I18N_DICT[txt];
      }
    }
  });
}

function requestDomTranslation(target) {
  if (!isEnglishActive()) return;
  if (translationTimeout) clearTimeout(translationTimeout);
  translationTimeout = setTimeout(function() {
    if (isTranslating) return;
    isTranslating = true;
    try {
      applyGlobalDomTranslations(target);
    } finally {
      isTranslating = false;
    }
  }, 25);
}

// Initialize DOM MutationObserver for seamless asynchronous translations
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', function() {
    if (window.MutationObserver) {
      const observer = new MutationObserver(function(mutations) {
        if (!isEnglishActive() || isTranslating) return;
        let hasNewNodes = false;
        for (let i = 0; i < mutations.length; i++) {
          if (mutations[i].type === 'childList' && mutations[i].addedNodes.length > 0) {
            hasNewNodes = true;
            break;
          }
        }
        if (hasNewNodes) {
          requestDomTranslation();
        }
      });
      observer.observe(document.body, { childList: true, subtree: true });
    }
  });
}

if (typeof window !== 'undefined') {
  window.applyGlobalDomTranslations = applyGlobalDomTranslations;
  window.translateText = translateText;
  window.isEnglishActive = isEnglishActive;
  window.requestDomTranslation = requestDomTranslation;
}
