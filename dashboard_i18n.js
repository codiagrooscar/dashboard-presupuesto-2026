function isEnglishActive() {
  return (typeof currentLang !== 'undefined' && currentLang === 'en');
}

function translateText(text) {
  if (!text || typeof text !== 'string') return text;
  if (!isEnglishActive()) return text;
  
  const trimmed = text.trim();
  if (window.CODIAGRO_I18N_DICT[trimmed]) {
    return text.replace(trimmed, window.CODIAGRO_I18N_DICT[trimmed]);
  }

  let out = text;
  for (let i = 0; i < window.CODIAGRO_I18N_PHRASES.length; i++) {
    const item = window.CODIAGRO_I18N_PHRASES[i];
    if (out.indexOf(item[0]) !== -1) {
      out = out.split(item[0]).join(item[1]);
    }
  }
  return out;
}

